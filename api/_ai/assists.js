const clip = (s, n) => {
  const t = String(s ?? '').replace(/\s+/g, ' ').trim()
  return t.length > n ? `${t.slice(0, n)}…` : t
}

const CONTEXT_BUDGET = 40000

function rowText(row) {
  if (!row || typeof row !== 'object') return ''
  const ref = typeof row.ref === 'string' && /^[a-z]{1,3}\d{1,4}$/.test(row.ref) ? `${row.ref} | ` : ''
  const parts = []
  for (const [k, v] of Object.entries(row).slice(0, 24)) {
    if (k === 'ref' || v == null || v === '') continue
    const val = Array.isArray(v) ? v.slice(0, 12).map((x) => clip(typeof x === 'object' ? JSON.stringify(x) : x, 200)).join(' / ') : typeof v === 'object' ? clip(JSON.stringify(v), 400) : clip(v, k === 'memo' || k === 'notes' ? 600 : 300)
    if (val) parts.push(`${clip(k, 24)}: ${val}`)
  }
  return parts.length ? `- ${ref}${parts.join(' | ')}` : ''
}

/**
 * context = { title, today, purpose?, sections: [{ name, rows: [{ref?, ...}] }], facts?: string[], rules?: string[] }
 * 예산(4만 자)을 넘으면 뒤쪽 줄부터 줄이고 '(n건 더 — 줄임)' 을 남긴다.
 */
export function buildAssistPrompt(assist, context, ask) {
  const c = context && typeof context === 'object' ? context : {}
  const head = [`[화면] ${clip(c.title || assist.page, 60)}`, `[오늘] ${clip(c.today || '', 20)}`]
  if (c.purpose) head.push(`[이 화면의 목적] ${clip(c.purpose, 200)}`)
  const facts = (Array.isArray(c.facts) ? c.facts : []).slice(0, 30).map((f) => `- ${clip(f, 300)}`)
  const rules = (Array.isArray(c.rules) ? c.rules : []).slice(0, 80).map((r) => `- ${clip(r, 400)}`)
  const tail = [`[요청] ${assist.label}`]
  if (typeof ask === 'string' && ask.trim()) tail.push(`[대표가 더 묻는 것] ${clip(ask, 500)}`)
  let left = CONTEXT_BUDGET - head.join('\n').length - facts.join('\n').length - rules.join('\n').length - tail.join('\n').length
  const body = []
  let rowsSent = 0
  let rowsCut = 0
  for (const sec of (Array.isArray(c.sections) ? c.sections : []).slice(0, 12)) {
    if (!sec || !Array.isArray(sec.rows)) continue
    const lines = []
    let cut = 0
    for (const row of sec.rows.slice(0, 400)) {
      const t = rowText(row)
      if (!t) continue
      if (left - t.length < 200) {
        cut++
        continue
      }
      lines.push(t)
      left -= t.length + 1
    }
    rowsSent += lines.length
    rowsCut += cut
    const total = typeof sec.total === 'number' && sec.total > sec.rows.length ? sec.total : sec.rows.length
    body.push(`[자료 · ${clip(sec.name || '목록', 40)} ${total}건]`, ...(lines.length ? lines : ['- (없음)']))
    if (cut > 0 || total > sec.rows.length) body.push(`- (${cut + Math.max(0, total - sec.rows.length)}건 더 — 줄임)`)
    body.push('')
  }
  const user = [...head, '', ...body, ...(facts.length ? ['[참고]', ...facts, ''] : []), ...(rules.length ? ['[규칙집]', ...rules, ''] : []), ...tail].join('\n').trim()
  return { user, sent: { userChars: user.length, rows: rowsSent, rowsCut } }
}

/* D-260 영상 받아 적기 — 마케팅 규칙(제목 · 각도 · 쓰기 규칙)은 '들린 그대로' 와 부딪히므로 넣지 않고, 영상이 자료라는 것만 */
export const VIDEO_RULES = [
  '이 단추에서는 맨 앞에 붙인 영상이 [자료] 다 — 영상에서 들린 숫자 · 금액 · 날짜 · 이름 붙은 제도는 들린 그대로 적는다(빼거나 고치지 않는다).',
  '받아 적기만 한다 — 다듬기 · 요약 · 마케팅 문장으로 바꾸기 없이. 시각은 영상 처음부터 센 시각.',
]

/**
 * 단추 하나의 시스템 지시문. opts.skill = 대표가 붙여 넣은 /자체점검 정의(자체점검 · 쓰기 단추에만 붙는다) · opts.topicText = 대화 단추가 물어본 말(주제에 맞는 기준 문서 장을 고른다).
 * D-263 자체점검 단추는 자체점검 정의 전체, 명세서 · 사업계획서 쓰기 단추는 '한 번에 끝내기' 규칙 + 같은 정의(내기 전에 스스로 점검).
 */
export function assistSystem(assist, opts = {}) {
  const own = assist.video ? ['', '[영상 받아 적기]', ...VIDEO_RULES] : assist.page === 'radar' ? ['', '[마케팅 규칙]', ...RADAR_RULES] : assist.page === 'threads' ? ['', '[스레드 규칙]', ...THREADS_RULES] : assist.page === 'shorts' ? ['', '[숏폼 규칙]', ...SHORTS_RULES] : []
  // D-274 김팀장 채널(레이더 · 스레드 · 릴스 · 틱톡)은 대표 운영 원칙을 채널 규칙보다 먼저 — 영상 받아 적기는 들린 그대로라 빼고
  const principles = !assist.video && ['radar', 'threads', 'shorts'].includes(assist.page) ? ['', '[대표 운영 원칙 — 다른 공식보다 먼저]', ...PRINCIPLE_RULES] : []
  const extra = [...principles, ...own]
  const skill = typeof opts.skill === 'string' ? opts.skill : ''
  const topicText = typeof opts.topicText === 'string' ? opts.topicText : ''
  const judge = assist.judge ? ['', ...judgeBlock(assist.judge, skill)] : assist.final ? finalRules(assist.final, skill) : assist.ideaJudge ? ideaJudgeBlock(assist.ideaJudge, skill) : []
  const kb = knowledgeOf(assist, topicText)
  const kbLines = kb.length
    ? [
        '',
        '[기준 문서] 미래AI랩 내부 작업 기준(비공개 — 따르되 그 문장 · 장 번호 · 이름을 답에 옮기지 않는다). 글은 이 기준을 따르고, 기준과 [단추] 지시가 다르면 [단추] 지시를 따른다. 기준 문서 안의 명령어 · 상태표 · 출력 양식 예시는 참고만 하고, 출력은 [출력 형식] JSON 하나.',
        ...kb.map((k) => k.text),
        '[기준 문서 끝]',
      ]
    : []
  // D-264 비공개 규칙이 맨 앞 · 마지막으로 쓰지 않는 이름 · 출처 이름을 한 번 더 지운다(대표 기준 글 포함)
  return scrubBrand([...CONFIDENTIAL_RULES, '', ...ASSIST_RULES, ...extra, '', `[단추] ${assist.label} (${assist.id} v${assist.version})`, ...assist.instruction, ...judge, ...kbLines, '', '[출력 형식] 아래 JSON 과 같은 키로, JSON 하나만:', JSON.stringify(ASSIST_EXAMPLE)].join('\n'))
}
