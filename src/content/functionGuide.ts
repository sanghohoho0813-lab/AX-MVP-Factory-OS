/** 이 메뉴 화면 안의 기능들(사용법 안내 화면에서 그 메뉴 줄 아래에 모아 보여 준다) */
export function functionGuidesOf(menu: string, opts: { pilot?: boolean; basic?: boolean; ownerAi?: boolean } = {}): Array<{ key: string; guide: FunctionGuide }> {
  return Object.entries(FUNCTION_GUIDES)
    .filter(([, g]) => g.menu === menu && !(opts.pilot && (g.hiddenForPilot || g.onlyOwner)) && !(opts.basic && g.basicHidden) && !(g.onlyOwner && opts.ownerAi === false))
    .map(([key, guide]) => ({ key, guide }))
}
