/** 메뉴 설명(hint)만 있는 줄 — '출시 예정' 항목 · AX 스튜디오 안 화면처럼 따로 적지 않은 메뉴 */
function fallback(label: string, hint: string | undefined, upcoming: boolean): MenuGuide {
  if (upcoming)
    return {
      what: `${label} 컨설팅을 모듈로 만드는 중이에요.`,
      why: '자주 하는 컨설팅을 도구로 만들어 두면 처음 하는 사람도 같은 품질로 할 수 있어서요.',
      effect: '준비되면 업체 숫자로 결과물(진단 · 설계서)이 바로 나와요.',
      next: '준비되는 대로 이 자리에서 열려요.',
    }
  return {
    what: hint ? `${hint}.`.replace(/\.\.$/, '.') : `${label} 화면이에요.`,
    why: '자주 하는 일을 한 자리에서 끝내려고요.',
    effect: '필요한 정보와 다음 할 일을 한 화면에서 볼 수 있어요.',
    next: VIDEO_SOON,
  }
}

/** 같은 화면을 가리키는 다른 메뉴 줄(웹 스튜디오 안 도구 줄 = 마케팅 안 화면) */
const SAME: Record<string, string> = { 'tool-homepage': 'mk-homepage', 'tool-content': 'mk-content' }

/** 이 메뉴의 안내 — basic 이면 전문 모듈이 없는 계정용 글 */
export function menuGuide(key: string, opts: { label?: string; hint?: string; basic?: boolean } = {}): MenuGuide {
  // D-569 화면 안 기능(fn-…)은 기능 안내에서
  const fn = FUNCTION_GUIDES[key]
  if (fn) {
    const base: MenuGuide = { what: fn.what, why: fn.why, effect: fn.effect, next: fn.next }
    return opts.basic && fn.basic ? { ...base, ...fn.basic } : base
  }
  const g = GUIDES[SAME[key] ?? key]
  if (!g) return fallback(opts.label ?? key, opts.hint, key.startsWith('up-'))
  const { basic, ...base } = g
  return opts.basic && basic ? { ...base, ...basic } : base
}

/** 따로 적어 둔 안내가 있는 메뉴인가(시험 · 목록용) */
export function hasMenuGuide(key: string): boolean {
  if (FUNCTION_GUIDES[key]) return true
  return (SAME[key] ?? key) in GUIDES
}

