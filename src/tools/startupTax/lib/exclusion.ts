import type { ExclusionReason, FormData } from '../types'

// 창업 제외사유 진단
// 조세특례제한법상 "창업으로 보지 않는 경우"를 형태별로 구체 설명한다.
// 단정하지 않고 "가능성 / 검토 필요" 톤을 유지한다.
export function diagnoseExclusion(form: FormData): ExclusionReason[] {
  switch (form.startupForm) {
    case 'conversion':
      return [
        {
          title: '개인사업자의 법인전환',
          detail:
            '거주자가 영위하던 개인사업을 법인으로 전환하여 새 법인을 설립하는 경우, 사업의 동일성이 유지되는 것으로 보아 신규 창업으로 인정되지 않을 가능성이 큽니다.',
          exception:
            '다만 전환 시점·자산 승계 범위·업종 변경 여부 등에 따라 판단이 달라질 수 있어, 전환 구조를 확인한 뒤 적용 여부를 검토할 필요가 있습니다.',
        },
      ]
    case 'acquisition':
      return [
        {
          title: '기존 사업의 양수',
          detail:
            '종전 사업자로부터 사업을 승계하거나, 종전 사업에 사용되던 자산을 인수·매입하여 같은 종류의 사업을 하는 경우는 창업에서 제외될 가능성이 높습니다.',
          exception:
            '양수한 자산의 비중, 종전 사업과의 동종 여부, 사업장·거래처 승계 여부 등에 따라 결론이 달라질 수 있어 거래 내역 확인이 필요합니다.',
        },
      ]
    case 'reopen_same':
      return [
        {
          title: '폐업 후 동종업 재창업',
          detail:
            '폐업 후 사업을 다시 개시하여 폐업 전과 같은 종류의 사업을 영위하는 경우, 사업의 단순 재개로 보아 창업으로 인정되지 않을 가능성이 있습니다.',
          exception:
            '폐업과 재개시 사이의 기간, 업종 동일성, 사업 규모·형태 변경 여부 등에 따라 달라질 수 있어 구체적 사실관계 확인이 필요합니다.',
        },
      ]
    case 'succession':
      return [
        {
          title: '특수관계인 사업 승계',
          detail:
            '가족 등 특수관계인이 영위하던 사업을 승계받는 경우, 사업의 실질적 이전으로 보아 창업으로 인정되지 않을 가능성이 매우 높습니다.',
          exception:
            '증여·상속·양수 등 승계 형태와 종전 사업과의 동종 여부에 따라 판단이 달라질 수 있으나, 일반적으로 창업감면 적용은 어렵다고 보고 접근하는 것이 안전합니다.',
        },
      ]
    case 'unknown':
      return [
        {
          title: '창업 형태 미확인',
          detail:
            '창업 형태가 확인되지 않아 법인전환·사업양수·동종 재창업·특수관계인 승계 등 제외사유 해당 여부를 판단할 수 없습니다.',
          exception:
            '실제 사업 개시 경위(신규/전환/양수/승계)를 먼저 확인해야 창업 인정 여부를 판단할 수 있습니다.',
        },
      ]
    case 'brand_new':
    default:
      return []
  }
}
