// 미팅 질문 5단계(라벨 + 질문). 흐름 정의가 없으면 전략 기본 questions로 폴백.
export function meetingQuestionFlow(strategy) {
  const f = strategy && MEETING_FLOW[strategy.name];
  if (f) {
    return [
      { step: "A", label: "오프닝", q: f.opening },
      { step: "B", label: "현황 확인", q: f.status },
      { step: "C", label: "문제 인식", q: f.problem },
      { step: "D", label: "제안 연결", q: f.connect },
      { step: "E", label: "다음 액션", q: f.action },
    ].filter((x) => x.q);
  }
  // 폴백: 기존 전략 questions(있으면)로 5단계 비슷하게 구성
  const qs = (strategy && strategy.questions) || [];
  const labels = [["A", "오프닝"], ["B", "현황 확인"], ["C", "문제 인식"], ["D", "제안 연결"], ["E", "다음 액션"]];
  return qs.slice(0, 5).map((q, i) => ({ step: labels[i][0], label: labels[i][1], q }));
}

// 제안 항목별 핵심 요청자료(흐름 정의 우선, 없으면 전략 docs).
export function meetingDocs(strategy) {
  const f = strategy && MEETING_FLOW[strategy.name];
  return (f && f.docs) || (strategy && strategy.docs) || [];
}
export function meetingShort(strategy) {
  const f = strategy && MEETING_FLOW[strategy.name];
  return (f && f.short) || (strategy && strategy.why) || "";
}
export function meetingEffect(strategy) {
  const f = strategy && MEETING_FLOW[strategy.name];
  if (f && f.effect) return f.effect;
  return ((strategy && strategy.effects) || []).join(" · ");
}

// 미팅 요청자료 기본 체크리스트(공통). 선택 항목별 docs와 합쳐 사용.
export const BASE_DOC_CHECKLIST = [
  "최근 3개년 재무제표", "부가세 신고자료", "원천세 신고자료", "4대보험 가입자명부",
  "주주명부", "정관", "법인등기부등본", "대출잔액증명서", "금융거래확인서",
  "연구인력·조직도", "인증서·특허·상표·디자인 보유자료",
];
// 선택 항목 기준 요청자료 체크리스트: 기본목록 + 선택항목 docs(강조), 중복 제거.
export function buildDocChecklist(selectedStrategies) {
  const emphasized = new Set();
  (selectedStrategies || []).forEach((s) => meetingDocs(s).forEach((d) => emphasized.add(d)));
  const norm = (s) => String(s).replace(/\s|·|\/|\(|\)/g, "");
  const baseNorm = new Set(BASE_DOC_CHECKLIST.map(norm));
  const list = BASE_DOC_CHECKLIST.map((d) => ({ name: d, emphasized: [...emphasized].some((e) => norm(e) === norm(d)) }));
  // 기본목록에 없는 선택항목 전용 자료는 뒤에 추가(강조)
  [...emphasized].forEach((e) => { if (!baseNorm.has(norm(e))) list.push({ name: e, emphasized: true, extra: true }); });
  return list;
}
