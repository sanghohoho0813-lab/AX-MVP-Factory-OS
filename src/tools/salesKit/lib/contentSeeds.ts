/** 주제 하나 → 채널별 문구 (블로그·카톡·콜드콜) */
export function channelTexts(seed: ContentSeed): { channel: string; text: string }[] {
  return [
    { channel: '블로그·유튜브 제목', text: seed.title },
    { channel: '첫 문단', text: `${seed.hook}\n\n${seed.cta}` },
    {
      channel: '카톡 한 줄',
      text: `${seed.title}\n대표님 회사도 해당되는지 3분이면 확인해 드립니다. 편하실 때 말씀 주세요.`,
    },
    {
      channel: '콜드콜 첫 문장',
      text: `대표님, ${seed.hook} 혹시 ${seed.cat} 관련해서 최근에 점검해 보신 적 있으세요?`,
    },
  ]
}

/** 벤치마킹 변환 — 단정하는 말을 눌러 제목 후보로 (원본 규칙 그대로) */
export function benchmarkTitles(text: string): string[] {
  if (!text.trim()) return []
  return [
    text.replace(/무조건|반드시/g, '먼저 확인해야 할'),
    '대표님, 이 순서 놓치면 나중에 비용이 더 커질 수 있습니다',
    '세무사가 있어도 대표님이 직접 챙겨야 하는 법인 체크포인트',
    '법인세 줄이기 전에 먼저 봐야 할 위험 신호',
    '가업승계·정관·가지급금, 미루면 왜 불리해질까?',
  ]
}
