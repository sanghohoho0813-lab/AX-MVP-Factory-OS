export interface TemplateVars {
  고객사명: string;
  월: string;
  기한: string;
}

/** 자리표시자 치환 — 비워 둔 값은 자리표시자를 그대로 남겨 어디를 채워야 하는지 보이게 한다 */
export function fillTemplate(body: string, vars: Partial<TemplateVars>): string {
  return body.replace(/\{(고객사명|월|기한)\}/g, (whole, key: keyof TemplateVars) => {
    const v = vars[key]?.trim();
    return v ? v : whole;
  });
}
