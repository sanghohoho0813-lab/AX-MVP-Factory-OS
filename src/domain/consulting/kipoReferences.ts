/** 선정 규칙: 2~5종, 중복 없음 */
export function kipoSelectionIssues(sel: KipoSelection[]): string[] {
  const issues: string[] = []
  const codes = sel.map((s) => s.code)
  if (new Set(codes).size !== codes.length) issues.push('같은 사례가 두 번 들어 있습니다.')
  if (sel.length < KIPO_MIN) issues.push(`참고자료는 최소 ${KIPO_MIN}종을 고릅니다 (지금 ${sel.length}종).`)
  if (sel.length > KIPO_MAX) issues.push(`참고자료는 최대 ${KIPO_MAX}종입니다 (지금 ${sel.length}종).`)
  const noReason = sel.filter((s) => s.reason.trim() === '').length
  if (noReason > 0) issues.push(`선정 이유가 없는 사례 ${noReason}종 — 기술분야·발명형태·처리구조·청구항/도면 중 무엇을 참고하는지 적습니다.`)
  const noPdf = sel.filter((s) => !s.pdfAttached).length
  if (sel.length > 0 && noPdf > 0) issues.push(`PDF 를 아직 받지 않은 사례 ${noPdf}종 — 받기 전에는 세부 문구를 추측해 명세서에 쓰지 않습니다.`)
  return issues
}

/** 사용자에게 보낼 첨부 요청문 (APPENDIX B 형식) */
export function kipoRequestText(sel: KipoSelection[]): string {
  const lines = sel
    .map((s) => kipoByCode(s.code))
    .filter((r): r is KipoReference => r !== null)
    .map((r) => `- ${r.code} — ${r.title}`)
  return `아래 KIPO 명세서 작성 예시 PDF 를 받아 첨부해 주세요.\n${lines.join('\n')}\n\n실제 문서 구조와 청구항·도면 표현을 비교한 뒤, 이번 회사 발명 내용으로 명세서를 새로 작성합니다.`
}
