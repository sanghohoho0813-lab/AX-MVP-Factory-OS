import type { RespondentRole } from './index'

/* ------------------------------------------------------------------ */
/* 진단 분석 도메인 타입 (Stage 5)                                       */
/*                                                                     */
/* 규칙 기반 진단 분석·AX 적합성 점수 산정 도메인.                        */
/* 모든 점수는 제출 응답과 사전 정의된 규칙으로 계산되며,                 */
/* 자동 계산값과 담당자 수동 보정값을 함께 보존한다.                     */
/* ------------------------------------------------------------------ */

/** 분석 결과 상태 */
export type AssessmentStatus = 'draft' | 'reviewed' | 'finalized' | 'superseded'

/** 최종 판정 (AX 프로젝트) */
export type AssessmentRecommendation =
  | 'ax_strongly_recommended'
  | 'simple_automation_recommended'
  | 'diagnosis_document_first'
  | 'funding_consulting_first'
  | 'build_deferred_data'
  | 'build_deferred_adoption'
  | 'expert_review_required'

/** AX 적합성 점수 영역 (결과에 쓰는 7개 영역) */
export type AssessmentDomain =
  | 'repetition'
  | 'economic'
  | 'data_readiness'
  | 'process_clarity'
  | 'adoption'
  | 'execution'
  | 'funding_connection'

/** 신뢰도 3단계 (영역 단위) */
export type ScoreConfidence = 'high' | 'medium' | 'low'

/** 분석 전체 신뢰도 (insufficient 포함) */
export type AssessmentConfidence = 'high' | 'medium' | 'low' | 'insufficient'

export interface DomainScore {
  domain: AssessmentDomain
  /** 원점수(영역 배점 환산) */
  rawScore: number
  /** 영역 최대 배점 */
  maxScore: number
  /** 0~100 정규화 점수 */
  normalizedScore: number
  evidenceCount: number
  /** 이 영역에 해당하는 점수 대상 문항 수(스냅샷 합집합) */
  applicableQuestionCount: number
  /** 실제 점수화된(응답된) 문항 수 */
  answeredQuestionCount: number
  confidence: ScoreConfidence
  evidenceIds: string[]
  explanation: string
  warnings: string[]
  /** 응답이 하나도 없어 점수 계산에서 제외된 영역 */
  measured: boolean
}

/* ------------------------------------------------------------------ */
/* 감점                                                                 */
/* ------------------------------------------------------------------ */

export type AssessmentDeductionType =
  | 'no_owner'
  | 'no_field_participant'
  | 'insufficient_data'
  | 'inconsistent_process'
  | 'high_privacy_risk'
  | 'expert_judgment_dominant'
  | 'no_measurable_kpi'
  | 'low_adoption_will'
  | 'formal_build_only'
  | 'severe_response_conflict'
  | 'custom'

export interface AssessmentDeduction {
  id: string
  type: AssessmentDeductionType
  label: string
  /** 양수로 저장하고 총점에서 차감한다 */
  points: number
  reason: string
  evidenceIds: string[]
  autoGenerated: boolean
  overridden: boolean
  overrideReason: string
}

/* ------------------------------------------------------------------ */
/* 근거(Evidence)                                                       */
/* ------------------------------------------------------------------ */

export type AssessmentEvidenceType =
  | 'answer'
  | 'calculated_metric'
  | 'conflict'
  | 'missing_data'
  | 'risk_signal'
  | 'manual_note'

export interface AssessmentEvidence {
  id: string
  projectId: string
  distributionId: string
  responseId: string
  respondentRole: RespondentRole
  respondentName: string
  questionId: string
  questionCode: string
  questionText: string
  category: string
  scoringDomain: string
  /** 사람이 읽을 수 있는 답변 표현 */
  answerValue: string
  /** 0~100 정규화 값 (점수화되지 않으면 null) */
  normalizedValue: number | null
  evidenceType: AssessmentEvidenceType
  weight: number
  /** 영역 점수 기여도(0~100 정규화 값에 가중치 반영한 표시용) */
  contribution: number
  explanation: string
  createdAt: string
}

/* ------------------------------------------------------------------ */
/* 응답자 비교                                                          */
/* ------------------------------------------------------------------ */

export type ResponseComparisonStatus =
  | 'aligned'
  | 'minor_gap'
  | 'major_gap'
  | 'insufficient'

export type ComparisonImportance = 'low' | 'medium' | 'high' | 'critical'

export interface ComparisonRespondentValue {
  role: RespondentRole
  respondentName: string
  displayValue: string
  normalizedValue: number | null
  responseId: string
}

export interface ResponseComparisonItem {
  id: string
  topicKey: string
  title: string
  description: string
  category: string
  relatedQuestionCodes: string[]
  respondentValues: ComparisonRespondentValue[]
  status: ResponseComparisonStatus
  /** 0~100, 차이가 클수록 큼 */
  gapScore: number
  importance: ComparisonImportance
  interpretation: string
  requiresInterview: boolean
  evidenceIds: string[]
}

/* ------------------------------------------------------------------ */
/* 이슈(모순·누락·위험)                                                  */
/* ------------------------------------------------------------------ */

export type AnalysisIssueType =
  | 'missing_data'
  | 'contradiction'
  | 'perception_gap'
  | 'risk_signal'
  | 'invalid_answer'
  | 'insufficient_response'
  | 'expert_review'
  | 'outlier'

export type AnalysisIssueSeverity = 'info' | 'warning' | 'critical'

export type AnalysisIssueStatus = 'open' | 'acknowledged' | 'resolved' | 'excluded'

export interface AnalysisIssue {
  id: string
  projectId: string
  type: AnalysisIssueType
  severity: AnalysisIssueSeverity
  title: string
  description: string
  relatedQuestionIds: string[]
  relatedResponseIds: string[]
  evidenceIds: string[]
  suggestedAction: string
  status: AnalysisIssueStatus
  resolutionNote: string
  resolvedAt: string | null
  /** 자동 생성 규칙 키 (재분석 시 자동 이슈 교체용) */
  ruleKey: string
  autoGenerated: boolean
  createdAt: string
  updatedAt: string
}

export type AnalysisIssueInput = Omit<
  AnalysisIssue,
  'id' | 'createdAt' | 'updatedAt'
>

/* ------------------------------------------------------------------ */
/* 추가 인터뷰 질문                                                      */
/* ------------------------------------------------------------------ */

export type InterviewQuestionPriority = 'low' | 'medium' | 'high' | 'critical'

export type InterviewQuestionStatus =
  | 'suggested'
  | 'selected'
  | 'answered'
  | 'excluded'

export interface InterviewQuestion {
  id: string
  projectId: string
  sourceIssueIds: string[]
  targetRespondentRole: RespondentRole
  priority: InterviewQuestionPriority
  question: string
  reason: string
  expectedEvidence: string
  status: InterviewQuestionStatus
  manual: boolean
  answer: string
  answeredAt: string | null
  /** 자동 생성 규칙 키 (재생성 시 교체용) */
  ruleKey: string
  createdAt: string
  updatedAt: string
}

export type InterviewQuestionInput = Omit<
  InterviewQuestion,
  'id' | 'createdAt' | 'updatedAt'
>

