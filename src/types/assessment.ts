export type WebsiteReadinessDomain =
  | 'purpose_clarity'
  | 'customer_clarity'
  | 'content_readiness'
  | 'brand_direction'
  | 'asset_readiness'
  | 'operation_readiness'

export type WebsiteReadinessRecommendation =
  | 'design_ready'
  | 'content_supplement'
  | 'structure_first'
  | 'planning_interview_first'

export interface WebsiteReadinessScore {
  domain: WebsiteReadinessDomain
  score: number
  maxScore: number
  confidence: ScoreConfidence
  evidenceIds: string[]
  explanation: string
}

export interface WebsiteReadinessResult {
  overallScore: number
  recommendation: WebsiteReadinessRecommendation
  confidence: AssessmentConfidence
  domains: WebsiteReadinessScore[]
  missingAssets: string[]
  missingContent: string[]
  designRisks: string[]
  nextActions: string[]
}

/* ------------------------------------------------------------------ */
/* 분석 결과 (AssessmentResult)                                          */
/* ------------------------------------------------------------------ */

export interface AssessmentResult {
  id: string
  projectId: string
  organizationId: string
  version: number
  status: AssessmentStatus
  /** 분석 대상 유형 */
  analysisKind: 'ax' | 'website' | 'ax_website'
  sourceResponseIds: string[]
  sourceDistributionIds: string[]
  /** 사용한 응답 스냅샷 해시 (재분석 필요 판정용) */
  sourceSnapshotHash: string

  domainScores: DomainScore[]
  /** 점수 근거 (계산 시점 동결) */
  evidence: AssessmentEvidence[]
  /** 응답자 비교 (계산 시점 동결) */
  comparisons: ResponseComparisonItem[]
  subtotalScore: number
  deductions: AssessmentDeduction[]
  deductionTotal: number
  finalScore: number
  recommendation: AssessmentRecommendation
  /** 점수 구간에 따른 기본 판정 (예외 적용 전) */
  baseRecommendation: AssessmentRecommendation
  /** 예외 판정이 적용된 이유 (없으면 빈 문자열) */
  recommendationExceptionReason: string
  confidence: AssessmentConfidence
  confidenceReason: string
  dataCompleteness: number
  respondentCoverage: number
  scoreCoverage: number

  keyStrengths: string[]
  keyWeaknesses: string[]
  keyRisks: string[]
  missingDataSummary: string[]
  conflictSummary: string[]
  suggestedNextActions: string[]

  autoSummary: string
  manualSummary: string
  manualAdjustments: ManualScoreAdjustment[]

  /** 홈페이지 준비도 (website / ax_website 프로젝트) */
  websiteReadiness: WebsiteReadinessResult | null

  ruleVersion: string
  createdBy: string
  reviewedBy: string
  finalizedBy: string
  createdAt: string
  updatedAt: string
  reviewedAt: string | null
  finalizedAt: string | null
}

export type AssessmentResultInput = Omit<
  AssessmentResult,
  'id' | 'version' | 'createdAt' | 'updatedAt'
>

export interface AssessmentFilters {
  query?: string
  projectType?: 'ax' | 'ax_website' | 'website'
  status?: AssessmentStatus
  recommendation?: AssessmentRecommendation
  confidence?: AssessmentConfidence
  /** 점수 구간 하한/상한 */
  minScore?: number
  maxScore?: number
  needsReanalysis?: boolean
  ownerId?: string
}

export type AssessmentSortKey =
  | 'recent'
  | 'score_desc'
  | 'score_asc'
  | 'confidence_desc'
  | 'client_name'
