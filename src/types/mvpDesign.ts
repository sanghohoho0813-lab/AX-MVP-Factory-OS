/* T. MVP 수준 결정 */
export interface MvpLevelDecision {
  recommendedLevel: MvpLevel
  selectedLevel: MvpLevel
  /** 추천과 다른 수준을 선택했을 때의 사유(필수) */
  overrideReason: string
  rationale: string
}

/* U. 설계 집계 루트 */
