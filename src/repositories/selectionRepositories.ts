export class LocalSelectionHandoffRepository
  implements SelectionHandoffRepository
{
  private read(): SelectionHandoffSnapshot[] {
    return readList<SelectionHandoffSnapshot>(STORAGE_KEYS.selectionHandoffs)
  }
  private write(list: SelectionHandoffSnapshot[]): void {
    writeJson(STORAGE_KEYS.selectionHandoffs, list)
    notifyStoreChanged()
  }

  getAll(): SelectionHandoffSnapshot[] {
    return this.read()
  }
  getByProjectId(projectId: string): SelectionHandoffSnapshot[] {
    return this.read().filter((h) => h.projectId === projectId)
  }
  getBySelectionDecisionId(selectionDecisionId: string): SelectionHandoffSnapshot | null {
    return this.read().find((h) => h.selectionDecisionId === selectionDecisionId) ?? null
  }

  create(snapshot: SelectionHandoffInput): SelectionHandoffSnapshot {
    const created: SelectionHandoffSnapshot = { ...snapshot, id: generateId() }
    this.write([...this.read(), created])
    return created
  }

  replaceForDecision(
    selectionDecisionId: string,
    snapshot: SelectionHandoffInput,
  ): SelectionHandoffSnapshot {
    const kept = this.read().filter((h) => h.selectionDecisionId !== selectionDecisionId)
    const created: SelectionHandoffSnapshot = { ...snapshot, id: generateId() }
    this.write([...kept, created])
    return created
  }
}
