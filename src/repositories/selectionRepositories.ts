export class LocalSelectionDecisionRepository
  implements SelectionDecisionRepository
{
  private read(): SelectionDecision[] {
    return readList<SelectionDecision>(STORAGE_KEYS.selectionDecisions)
  }
  private write(list: SelectionDecision[]): void {
    writeJson(STORAGE_KEYS.selectionDecisions, list)
    notifyStoreChanged()
  }

  getAll(): SelectionDecision[] {
    return this.read()
  }
  getById(id: string): SelectionDecision | null {
    return this.read().find((d) => d.id === id) ?? null
  }
  getByProjectId(projectId: string): SelectionDecision[] {
    return this.read()
      .filter((d) => d.projectId === projectId)
      .sort((a, b) => b.version - a.version)
  }
  getLatestByProjectId(projectId: string): SelectionDecision | null {
    const list = this.getByProjectId(projectId)
    if (list.length === 0) return null
    return list.find((d) => d.status !== 'superseded') ?? list[0]
  }
  nextVersion(projectId: string): number {
    return this.getByProjectId(projectId).reduce((m, d) => Math.max(m, d.version), 0) + 1
  }

  create(input: SelectionDecisionInput): SelectionDecision {
    const ts = nowIso()
    const decision: SelectionDecision = {
      ...input,
      id: generateId(),
      version: this.nextVersion(input.projectId),
      createdAt: ts,
      updatedAt: ts,
    }
    this.write([...this.read(), decision])
    return decision
  }

  update(id: string, input: Partial<SelectionDecisionInput>): SelectionDecision {
    const list = this.read()
    const index = list.findIndex((d) => d.id === id)
    if (index < 0) throw new EntityNotFoundError('선정 결과')
    const updated: SelectionDecision = {
      ...list[index],
      ...input,
      id,
      version: list[index].version,
      updatedAt: nowIso(),
    }
    list[index] = updated
    this.write(list)
    return updated
  }

  markReviewed(id: string, reviewerName: string): SelectionDecision {
    return this.update(id, { status: 'reviewed', reviewedBy: reviewerName, reviewedAt: nowIso() })
  }

  finalize(id: string, finalizerName: string): SelectionDecision {
    const target = this.getById(id)
    if (!target) throw new EntityNotFoundError('선정 결과')
    const ts = nowIso()
    const next = this.read().map((d) => {
      if (d.projectId === target.projectId && d.id !== id && d.status === 'finalized') {
        return { ...d, status: 'superseded' as const, supersededAt: ts, updatedAt: ts }
      }
      if (d.id === id) {
        return { ...d, status: 'finalized' as const, finalizedBy: finalizerName, finalizedAt: ts, updatedAt: ts }
      }
      return d
    })
    this.write(next)
    return next.find((d) => d.id === id) as SelectionDecision
  }

  supersede(id: string): SelectionDecision {
    return this.update(id, { status: 'superseded', supersededAt: nowIso() })
  }

  search(filters: SelectionFilters): SelectionDecision[] {
    const query = normalizeQuery(filters.query ?? '')
    return this.read().filter((d) => {
      if (filters.status && d.status !== filters.status) return false
      if (query) {
        const haystack = `${d.decisionSummary} ${d.autoSummary}`.toLowerCase()
        if (!haystack.includes(query)) return false
      }
      return true
    })
  }
}

