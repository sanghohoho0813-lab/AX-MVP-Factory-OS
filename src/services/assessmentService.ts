export class NoSubmittedResponseError extends Error {
  constructor() {
    super('제출 완료된 설문 응답이 없습니다.')
    this.name = 'NoSubmittedResponseError'
  }
}

/**
 * 분석을 실행하거나 갱신한다.
 * - 최신 분석이 없으면 새로 생성
 * - 최신이 draft/reviewed면 제자리 갱신(수동 보정·요약은 유지하지 않고 새로 계산)
 * - 최신이 finalized면 새 버전 draft 생성
 */
export function runOrRefreshAnalysis(projectId: string): AssessmentResult {
  const dataset = gatherAnalysisDataset(projectId)
  if (!dataset || dataset.respondents.length === 0) {
    throw new NoSubmittedResponseError()
  }
  const analyzedAt = nowIso()
  const { resultInput, issues, interviewQuestions } = runAssessmentAnalysis(
    dataset,
    analyzedAt,
  )

  const latest = assessmentRepository.getLatestByProjectId(projectId)
  let saved: AssessmentResult
  if (!latest || latest.status === 'finalized') {
    saved = assessmentRepository.create(resultInput)
  } else {
    // draft/reviewed 갱신 — 상태는 draft로 되돌림(재계산)
    saved = assessmentRepository.update(latest.id, {
      ...resultInput,
      status: 'draft',
      manualSummary: latest.manualSummary,
    })
  }

  // 자동 이슈·인터뷰 질문 교체(수동·처리된 항목 보존)
  analysisIssueRepository.replaceAutoGenerated(projectId, issues)
  interviewQuestionRepository.replaceAutoGenerated(projectId, interviewQuestions)

  activityRepository.add({
    organizationId: saved.organizationId,
    projectId,
    activityType: 'project_updated',
    title: 'AX 진단 분석이 실행되었습니다.',
    description:
      saved.analysisKind === 'website'
        ? `홈페이지 제작 준비도 ${saved.websiteReadiness?.overallScore ?? 0}점 (초안)`
        : `최종 점수 ${saved.finalScore}점 · ${RECOMMENDATION_META[saved.recommendation].label} (초안)`,
    actorName: CURRENT_USER.name,
  })

  return saved
}

