export type AnalysisLifecycle =
  | 'no_response'
  | 'ready_to_analyze'
  | 'draft'
  | 'reviewed'
  | 'finalized'
  | 'needs_reanalysis'

/** 프로젝트의 제출 응답 수 */
export function countSubmittedResponses(projectId: string): number {
  return surveyResponseRepository
    .search({ projectId, status: 'submitted' })
    .length
}

/** 현재 제출 응답 집합의 스냅샷 해시 */
function currentSubmittedHash(projectId: string): string {
  const ids = surveyResponseRepository
    .search({ projectId, status: 'submitted' })
    .map((r) => r.id)
  return computeSnapshotHash(ids)
}

/**
 * 확정/최신 분석이 현재 응답·인터뷰 답변보다 오래되어 재분석이 필요한지 판단한다.
 */
export function needsReanalysis(assessment: AssessmentResult): boolean {
  const currentHash = currentSubmittedHash(assessment.projectId)
  if (currentHash !== assessment.sourceSnapshotHash) return true
  // 분석 이후 새로 기록된 인터뷰 답변이 있으면 재분석 권장
  const interviews = interviewQuestionRepository.getByProjectId(
    assessment.projectId,
  )
  return interviews.some(
    (q) =>
      q.status === 'answered' &&
      q.answeredAt !== null &&
      q.answeredAt > assessment.updatedAt,
  )
}

export function getProjectAnalysisLifecycle(project: Project): AnalysisLifecycle {
  const submitted = countSubmittedResponses(project.id)
  if (submitted === 0) return 'no_response'
  const latest = assessmentRepository.getLatestByProjectId(project.id)
  if (!latest) return 'ready_to_analyze'
  if (needsReanalysis(latest)) return 'needs_reanalysis'
  if (latest.status === 'finalized') return 'finalized'
  if (latest.status === 'reviewed') return 'reviewed'
  return 'draft'
}

