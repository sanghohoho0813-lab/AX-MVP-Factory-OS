function recomputeTotals(result: AssessmentResult): {
  subtotalScore: number
  deductionTotal: number
  finalScore: number
  recommendation: AssessmentResult['recommendation']
} {
  const measured = result.domainScores.filter((d) => d.measured)
  const measuredMax = measured.reduce((s, d) => s + d.maxScore, 0)
  const measuredRaw = measured.reduce((s, d) => s + d.rawScore, 0)
  const subtotalScore =
    measuredMax > 0
      ? Math.max(0, Math.min(100, Math.round((measuredRaw / measuredMax) * 100)))
      : 0
  const deductionTotal = result.deductions
    .filter((d) => !d.overridden)
    .reduce((s, d) => s + d.points, 0)
  const finalScore = Math.max(0, Math.min(100, subtotalScore - deductionTotal))
  // 예외 판정이 적용된 경우 유지, 아니면 점수 구간 재계산
  const recommendation =
    result.recommendationExceptionReason !== ''
      ? result.recommendation
      : recommendationForScore(finalScore)
  return { subtotalScore, deductionTotal, finalScore, recommendation }
}

export class InvalidAdjustmentError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'InvalidAdjustmentError'
  }
}

/**
 * 영역별 수동 점수 보정.
 * - 0 이상, 영역 최대점 이하
 * - 사유 필수
 * - 자동 계산값(beforeScore) 보존
 */
export function applyManualScoreAdjustment(
  assessmentId: string,
  domain: AssessmentDomain,
  afterScore: number,
  reason: string,
): AssessmentResult {
  const result = assessmentRepository.getById(assessmentId)
  if (!result) throw new InvalidAdjustmentError('분석 결과를 찾을 수 없습니다.')
  if (result.status === 'finalized') {
    throw new InvalidAdjustmentError('확정된 결과는 수정할 수 없습니다.')
  }
  if (reason.trim() === '') {
    throw new InvalidAdjustmentError('보정 사유를 입력해야 합니다.')
  }
  const target = result.domainScores.find((d) => d.domain === domain)
  if (!target) throw new InvalidAdjustmentError('영역을 찾을 수 없습니다.')
  if (afterScore < 0 || afterScore > target.maxScore) {
    throw new InvalidAdjustmentError(
      `보정 점수는 0 ~ ${target.maxScore} 범위여야 합니다.`,
    )
  }

  const beforeScore = target.rawScore
  const rounded = Math.round(afterScore * 10) / 10
  const newDomainScores = result.domainScores.map((d) =>
    d.domain === domain
      ? {
          ...d,
          rawScore: rounded,
          normalizedScore:
            d.maxScore > 0 ? Math.round((rounded / d.maxScore) * 100) : 0,
          measured: true,
        }
      : d,
  )
  const adjustment: ManualScoreAdjustment = {
    id: `adj-${domain}-${result.manualAdjustments.length + 1}`,
    domain,
    beforeScore,
    afterScore: rounded,
    reason: reason.trim(),
    actorName: CURRENT_USER.name,
    createdAt: nowIso(),
  }

  const withAdjustment: AssessmentResult = {
    ...result,
    domainScores: newDomainScores,
    manualAdjustments: [...result.manualAdjustments, adjustment],
  }
  const totals = recomputeTotals(withAdjustment)

  return assessmentRepository.update(assessmentId, {
    domainScores: newDomainScores,
    manualAdjustments: withAdjustment.manualAdjustments,
    ...totals,
  })
}

/** 자동 감점 제외/복원 (담당자 판단) */
export function toggleDeductionOverride(
  assessmentId: string,
  deductionId: string,
  overridden: boolean,
  overrideReason: string,
): AssessmentResult {
  const result = assessmentRepository.getById(assessmentId)
  if (!result) throw new InvalidAdjustmentError('분석 결과를 찾을 수 없습니다.')
  if (result.status === 'finalized') {
    throw new InvalidAdjustmentError('확정된 결과는 수정할 수 없습니다.')
  }
  if (overridden && overrideReason.trim() === '') {
    throw new InvalidAdjustmentError('감점 제외 사유를 입력해야 합니다.')
  }
  const newDeductions = result.deductions.map((d) =>
    d.id === deductionId
      ? { ...d, overridden, overrideReason: overridden ? overrideReason.trim() : '' }
      : d,
  )
  const totals = recomputeTotals({ ...result, deductions: newDeductions })
  return assessmentRepository.update(assessmentId, {
    deductions: newDeductions,
    ...totals,
  })
}

