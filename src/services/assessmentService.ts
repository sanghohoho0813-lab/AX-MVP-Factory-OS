export interface ProjectAnalysisContext {
  project: Project
  latest: AssessmentResult | null
  issues: AnalysisIssue[]
  interviews: InterviewQuestion[]
  submittedCount: number
  lifecycle: AnalysisLifecycle
  needsReanalysisFlag: boolean
}

export function getProjectAnalysisContext(
  projectId: string,
): ProjectAnalysisContext | null {
  const project = projectRepository.getById(projectId)
  if (!project) return null
  const latest = assessmentRepository.getLatestByProjectId(projectId)
  return {
    project,
    latest,
    issues: analysisIssueRepository.getByProjectId(projectId),
    interviews: interviewQuestionRepository.getByProjectId(projectId),
    submittedCount: countSubmittedResponses(projectId),
    lifecycle: getProjectAnalysisLifecycle(project),
    needsReanalysisFlag: latest ? needsReanalysis(latest) : false,
  }
}
