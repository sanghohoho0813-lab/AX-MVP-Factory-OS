/** 수동 감점 추가 */
export function addManualDeduction(
  assessmentId: string,
  points: number,
  reason: string,
): AssessmentResult {
  const result = assessmentRepository.getById(assessmentId)
  if (!result) throw new InvalidAdjustmentError('분석 결과를 찾을 수 없습니다.')
  if (points <= 0) throw new InvalidAdjustmentError('감점은 1점 이상이어야 합니다.')
  if (reason.trim() === '') throw new InvalidAdjustmentError('감점 사유를 입력해야 합니다.')
  const newDeductions = [
    ...result.deductions,
    {
      id: `ded-custom-${result.deductions.length + 1}`,
      type: 'custom' as const,
      label: DEDUCTION_TYPE_LABEL.custom,
      points: Math.round(points),
      reason: reason.trim(),
      evidenceIds: [],
      autoGenerated: false,
      overridden: false,
      overrideReason: '',
    },
  ]
  const totals = recomputeTotals({ ...result, deductions: newDeductions })
  return assessmentRepository.update(assessmentId, {
    deductions: newDeductions,
    ...totals,
  })
}

