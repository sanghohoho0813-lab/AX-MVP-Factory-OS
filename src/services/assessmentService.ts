export interface FinalizeCheck {
  ok: boolean
  reasons: string[]
}

/** 진단 확정 가능 여부 검증 */
export function checkCanFinalize(
  result: AssessmentResult,
  issues: AnalysisIssue[],
): FinalizeCheck {
  const reasons: string[] = []
  const criticalOpen = issues.filter(
    (i) => i.severity === 'critical' && i.status === 'open',
  )
  if (criticalOpen.length > 0) {
    reasons.push(`중대 이슈 ${criticalOpen.length}건을 확인 또는 해결해야 합니다.`)
  }
  if (result.manualSummary.trim() === '') {
    reasons.push('내부 최종 의견을 작성해야 합니다.')
  }
  if (result.suggestedNextActions.length === 0) {
    reasons.push('다음 행동이 1개 이상 필요합니다.')
  }
  return { ok: reasons.length === 0, reasons }
}

export function markAssessmentReviewed(assessmentId: string): AssessmentResult {
  return assessmentRepository.markReviewed(assessmentId, CURRENT_USER.name)
}

export class FinalizeBlockedError extends Error {
  constructor(reasons: string[]) {
    super(reasons.join(' '))
    this.name = 'FinalizeBlockedError'
  }
}

export function finalizeAssessment(assessmentId: string): AssessmentResult {
  const result = assessmentRepository.getById(assessmentId)
  if (!result) throw new FinalizeBlockedError(['분석 결과를 찾을 수 없습니다.'])
  const issues = analysisIssueRepository.getByProjectId(result.projectId)
  const check = checkCanFinalize(result, issues)
  if (!check.ok) throw new FinalizeBlockedError(check.reasons)

  const finalized = assessmentRepository.finalize(assessmentId, CURRENT_USER.name)

  const project = projectRepository.getById(result.projectId)
  activityRepository.add({
    organizationId: result.organizationId,
    projectId: result.projectId,
    activityType: 'status_changed',
    title: 'AX 진단 결과가 확정되었습니다.',
    description:
      finalized.analysisKind === 'website'
        ? `홈페이지 제작 준비도 ${finalized.websiteReadiness?.overallScore ?? 0}점`
        : `최종 점수 ${finalized.finalScore}점, 판정: ${RECOMMENDATION_META[finalized.recommendation].label}${project ? '' : ''}`,
    actorName: CURRENT_USER.name,
  })

  return finalized
}

