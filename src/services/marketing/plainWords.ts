/**
 * D-507 마케팅 화면 쉬운 말 — 대표 "60대 이상이 처음 딱 봐도 이해하기 쉽게".
 * 글(초안 · 복사되는 글)은 그대로 두고, 화면에 보이는 칸 이름만 쉬운 말로 바꿔 보여 준다.
 * 예전 이름은 괄호로 남긴다(유튜브 · 인스타 화면에서 보는 말과 이어지게).
 */
const PLAIN: ReadonlyArray<readonly [RegExp, string]> = [
  [/썸네일 문구/g, '표지 글(썸네일)'],
  [/제목 · 썸네일(?! 문구)/g, '제목 · 표지 글(썸네일)'],
  [/^썸네일$/g, '표지 그림(썸네일)'],
  [/^캡션$/g, '설명 글(캡션)'],
  [/인스타 캡션/g, '인스타 설명 글(캡션)'],
  [/^해시태그$/g, '#태그(해시태그)'],
  [/롱폼/g, '긴 영상'],
  [/숏폼/g, '짧은 영상'],
  [/^훅$/g, '첫마디'],
  [/\bCTA\b/g, '마지막 한마디(CTA)'],
]

/** 칸 이름 하나를 쉬운 말로 — 이미 괄호로 풀어 쓴 이름은 그대로 */
export function plainLabel(label: string): string {
  if (/\((썸네일|캡션|해시태그|CTA)\)/.test(label)) return label
  return PLAIN.reduce((s, [re, to]) => s.replace(re, to), label)
}
