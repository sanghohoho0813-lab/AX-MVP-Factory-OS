export interface TermPiece {
  text: string
  /** 사전에 있는 말이면 그 말 */
  term?: string
}

const KEYS = Object.keys(CONSULT_TERMS).sort((a, b) => b.length - a.length)
const RE = new RegExp(KEYS.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g')

/**
 * 글을 조각으로 — 사전에 있는 말은 따로(긴 말 먼저: '통합고용세액공제' 가 '세액공제' 보다 먼저).
 * 같은 글 안에서는 처음 한 번만 밑줄(같은 말이 줄마다 밑줄이면 읽기 어렵다). seen 을 넘기면 여러 글에 걸쳐 한 번만.
 */
export function splitTerms(text: string, seen: Set<string> = new Set()): TermPiece[] {
  const out: TermPiece[] = []
  let last = 0
  for (const m of text.matchAll(RE)) {
    const at = m.index ?? 0
    const term = m[0]
    if (seen.has(term)) continue
    seen.add(term)
    if (at > last) out.push({ text: text.slice(last, at) })
    out.push({ text: term, term })
    last = at + term.length
  }
  if (last < text.length) out.push({ text: text.slice(last) })
  return out
}
